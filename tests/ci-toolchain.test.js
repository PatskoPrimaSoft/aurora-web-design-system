import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const workflow=readFileSync(process.argv[2]??new URL('../.github/workflows/ci.yml',import.meta.url),'utf8');
const setup=workflow.search(/uses:\s*jdx\/mise-action@/);
assert.ok(setup>=0 && setup<workflow.indexOf('- name: Verify'),'CI must install mise before executing configured guard hooks');
assert.match(workflow,/tag_status.*\n\s+git ls-remote[^\n]+\|\| tag_status=\$\?/,'release guard must capture remote tag failures');
assert.match(workflow,/\[ "\$tag_status" -ne 2 \]/,'only Git exit 2 means missing tag');
assert.match(workflow,/node tools\/release-check\.mjs > \/dev\/null/,'CI must verify lock versions and release notes');
assert.match(workflow,/registry_state=\$\(node tools\/release-check\.mjs registry "\$VERSION"\)/,'registry failures must stop publication');
assert.match(workflow,/if \[ "\$registry_state" = present \]; then[\s\S]*else\s+npm publish/,'existing package must skip publication');
console.log('ci-toolchain: configured hook runtime installed before verification');
