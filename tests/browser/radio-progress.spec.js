import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {buildCatalogue} from '../../tools/catalog/build.mjs';
import {serveRoot} from '../../tools/baseline/render.mjs';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../../',import.meta.url));let served;
test.beforeAll(async()=>{await buildCatalogue({root,outDir:root+'/site'});served=await serveRoot(root+'/site');});
test.afterAll(async()=>{served?.server.closeAllConnections();if(served)await new Promise(r=>served.server.close(r));});
const scopes=[['DEFAULT','light','cozy'],['DEFAULT','dark','compact'],['RED2','light','cozy'],['RED2','dark','compact']];
for(const [theme,appearance,density] of scopes)test(`radio and progress preserve native interaction and narrow layout: ${theme}/${appearance}/${density}`,async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto(served.url+'/components/DsRadioGroup/preview.html?'+new URLSearchParams({theme,appearance,density}));
  const basic=page.locator('section[aria-labelledby="basic"]');
  await expect(basic.getByRole('radio',{name:'Только важные'})).toBeChecked();
  await basic.getByRole('radio',{name:'Только важные'}).focus();await page.keyboard.press('ArrowDown');
  await expect(basic.getByRole('radio',{name:'Не получать'})).toBeChecked();
  const form=page.locator('section[aria-labelledby="required-form"] [data-ds-example-demo]');
  await form.getByRole('button',{name:'Выбрать формат'}).click();
  await expect(form.getByText('Выберите один вариант.',{exact:true})).toBeVisible();
  await expect(form.getByRole('radio',{name:'CSV',exact:true})).toBeFocused();
  await page.keyboard.press('Space');await form.getByRole('button',{name:'Выбрать формат'}).click();
  await expect(form.getByRole('status')).toHaveText('Выбран формат: CSV');
  await form.getByRole('button',{name:'Сбросить',exact:true}).click();
  await expect(form.getByRole('radio',{name:'CSV',exact:true})).not.toBeChecked();
  await expect(form.getByRole('status')).toHaveText('');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect((await new AxeBuilder({page}).include('[data-ds-example-demo]').analyze()).violations).toEqual([]);
  await page.goto(served.url+'/components/DsProgressBar/preview.html?'+new URLSearchParams({theme,appearance,density}));
  const bar=page.getByRole('progressbar',{name:'Экспорт объектов',exact:true});
  await expect(bar).toHaveAttribute('aria-valuenow','0');
  await page.getByRole('button',{name:'Начать экспорт'}).click();
  await expect(bar).toHaveAttribute('aria-valuenow','500');
  await expect(page.locator('section[aria-labelledby="export"] [data-ds-example-demo]').getByRole('status')).toHaveText('Экспорт завершён.');
  const unknown=page.getByRole('progressbar',{name:'Подготовка отчёта'});
  await expect(unknown).not.toHaveAttribute('aria-valuenow',/.+/);
  await page.emulateMedia({reducedMotion:'reduce'});
  await expect(unknown.locator('[data-ds-progress-fill]')).toHaveCSS('animation-name','none');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect((await new AxeBuilder({page}).include('[data-ds-example-demo]').analyze()).violations).toEqual([]);
});
