test('copy writes the exact highlighted source, including whitespace, to the clipboard',async({page,context})=>{
  await context.grantPermissions(['clipboard-read','clipboard-write'],{origin:served.url});
  await page.goto(served.url+'/index.html?card=DsCheckbox');
  const block=page.locator('.code-block').first();
  await expect(block).toBeVisible();
  const expected=readFileSync(root+'/components/DsCheckbox/README.md','utf8').match(/```jsx\r?\n([\s\S]*?)```/)[1].replaceAll('\r\n','\n');
  expect(await block.locator('code').textContent()).toBe(expected);
  expect(await block.locator('code span').count()).toBeGreaterThan(0);
  await block.getByRole('button',{name:'Копировать код',exact:true}).click();
  await expect(block.getByRole('status')).toHaveText('Скопировано');
  // The Windows clipboard translates LF to CRLF; indentation and blank lines must survive.
  expect((await page.evaluate(()=>navigator.clipboard.readText())).replaceAll('\r\n','\n')).toBe(expected);
  await page.goto(served.url+'/api/components/DsCheckbox.html');
  await expect(page.locator('.code-block').getByRole('button',{name:'Копировать код',exact:true})).toBeVisible();
});

