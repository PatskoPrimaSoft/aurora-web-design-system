test('each live example has collapsible highlighted code that copies its source and preserves interaction',async({page,context},testInfo)=>{
  await context.grantPermissions(['clipboard-read','clipboard-write'],{origin:served.url});
  await page.setViewportSize({width:1500,height:950});
  await page.goto(served.url+'/index.html?card=DsCheckbox');
  const preview=page.frameLocator('#preview');
  await expect(preview.locator('.example-code')).toHaveCount(6);
  const sources=JSON.parse(readFileSync(root+'/components/DsCheckbox/examples.json','utf8'));
  for(const [id,source]of Object.entries(sources)){
    const example=preview.locator('section').filter({has:preview.locator('#'+id)});
    const disclosure=example.locator('.example-code summary');
    await expect(disclosure).toHaveText('Показать код',{useInnerText:true});
    await expect(example.locator('pre')).toBeHidden();
    await disclosure.focus();await page.keyboard.press('Enter');
    await expect(disclosure).toHaveText('Скрыть код',{useInnerText:true});
    await expect(example.locator('pre')).toBeVisible();
    expect(await example.locator('pre code').textContent()).toBe(source);
    expect(await example.locator('pre code span').count()).toBeGreaterThan(0);
    await example.getByRole('button',{name:'Копировать код',exact:true}).click();
    await expect(example.locator('.code-copy-status')).toHaveText('Скопировано');
    expect((await page.evaluate(()=>navigator.clipboard.readText())).replaceAll('\r\n','\n')).toBe(source);
    await disclosure.click();
  }
  const first=preview.getByRole('region',{name:'Обычный выбор',exact:true});
  const checkbox=first.getByRole('checkbox');await checkbox.focus();await page.keyboard.press('Space');
  await first.locator('summary').click();
  await chooseCatalogueScope(page,'appearance','dark');
  await expect(checkbox).not.toBeChecked();
  await expect(first.locator('details')).toHaveAttribute('open','');
  await expect(preview.getByRole('region',{name:'Частичный выбор',exact:true}).locator('h3')).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  const width=await first.locator('pre').evaluate(node=>({client:node.clientWidth,scroll:node.scrollWidth}));
  expect(width.scroll).toBeGreaterThan(width.client);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  expect(await preview.locator('body').evaluate(node=>node.scrollWidth)).toBeLessThanOrEqual(350);
  await first.locator('pre').focus();await expect(first.locator('pre')).toBeFocused();
  await page.screenshot({path:testInfo.outputPath('example-code-mobile.png')});
  await page.goto(served.url+'/components/DsCheckbox/preview.html');
  await page.locator('.example-code summary').first().click();
  await expect(page.locator('.example-code pre').first()).toBeVisible();
});

