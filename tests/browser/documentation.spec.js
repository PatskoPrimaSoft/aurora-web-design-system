test('contents navigate sections, follow scrolling and restore a shared section link',async({page},testInfo)=>{
  await page.setViewportSize({width:1500,height:950});
  await page.goto(served.url+'/index.html?card=DsCheckbox&theme=RED2&appearance=dark&density=compact');
  const toc=page.getByRole('navigation',{name:'На этой странице'});
  await expect(toc).toBeVisible();
  await expect(toc.getByRole('link')).toHaveText(['Живые примеры','Обычный выбор','Частичный выбор','Недоступное действие','Один вариант из группы','Выбор без подписи','Сравнение состояний','Правила применения','Пример кода','Параметры','Токены']);
  const codeLink=toc.getByRole('link',{name:'Пример кода',exact:true});
  await codeLink.focus();await page.keyboard.press('Enter');
  await expect(page.getByRole('heading',{name:'Пример кода',exact:true})).toBeFocused();
  await expect(codeLink).toHaveAttribute('aria-current','location');
  const destination=page.url();
  expect(new URL(destination).searchParams.get('appearance')).toBe('dark');
  expect(decodeURIComponent(new URL(destination).hash)).toBe('#пример-кода');
  await page.reload();
  await expect(toc.getByRole('link',{name:'Пример кода',exact:true})).toHaveAttribute('aria-current','location');
  const headingOffset=()=>page.getByRole('heading',{name:'Пример кода',exact:true}).evaluate(node=>node.getBoundingClientRect().top-document.querySelector('main').getBoundingClientRect().top);
  await expect.poll(headingOffset).toBeGreaterThanOrEqual(0);
  await expect.poll(headingOffset).toBeLessThan(60);
  await page.screenshot({path:testInfo.outputPath('code-desktop.png')});
  await toc.getByRole('link',{name:'Токены',exact:true}).click();
  await page.goBack();
  await expect(toc.getByRole('link',{name:'Пример кода',exact:true})).toHaveAttribute('aria-current','location');
  await page.locator('main').evaluate(node=>node.scrollTop=node.scrollHeight);
  await expect(toc.getByRole('link',{name:'Токены',exact:true})).toHaveAttribute('aria-current','location');
  await page.locator('main').evaluate(node=>node.scrollTop=0);
  await expect(toc.getByRole('link',{name:'Живые примеры',exact:true})).toHaveAttribute('aria-current','location');
  await chooseCatalogueScope(page,'appearance','light');
  await expect(page.frameLocator('#preview').locator('html')).toHaveAttribute('data-ds-appearance','light');
  await expect.poll(()=>page.locator('main').evaluate(node=>node.scrollTop)).toBe(0);
  expect((await new AxeBuilder({page}).exclude('iframe').analyze()).violations).toEqual([]);
  await page.locator('nav a[data-id="DsTabs"]').click();
  await expect(page.locator('#title')).toHaveText('DsTabs');
  await expect(toc.getByRole('link',{name:'Токены',exact:true})).toHaveCount(1);
  await page.goto(served.url+'/index.html?card=missing');
  await expect(toc).toHaveCount(0);
});

test('example contents navigate into the preview, restore links and stay unique in comparison',async({page})=>{
  await page.setViewportSize({width:1500,height:950});
  await page.goto(served.url+'/index.html?card=DsCheckbox');
  const toc=page.getByRole('navigation',{name:'На этой странице'});
  const partial=toc.getByRole('link',{name:'Частичный выбор',exact:true});
  await expect(toc.locator('ul ul a')).toHaveCount(6);
  await partial.focus();await page.keyboard.press('Enter');
  const heading=page.frameLocator('#preview').getByRole('heading',{name:'Частичный выбор',exact:true});
  await expect(heading).toBeFocused();
  await expect(partial).toHaveAttribute('aria-current','location');
  expect(new URL(page.url()).hash).toBe('#example-partial-selection');
  const offset=()=>heading.evaluate(node=>node.getBoundingClientRect().top+window.frameElement.getBoundingClientRect().top-parent.document.querySelector('main').getBoundingClientRect().top);
  await expect.poll(offset).toBeGreaterThanOrEqual(0);
  await expect.poll(offset).toBeLessThan(60);
  await page.reload();
  await expect(partial).toHaveAttribute('aria-current','location');
  await expect.poll(offset).toBeGreaterThanOrEqual(0);
  await expect.poll(offset).toBeLessThan(60);
  await toc.getByRole('link',{name:'Выбор без подписи',exact:true}).click();
  await page.goBack();
  await expect(partial).toHaveAttribute('aria-current','location');
  await page.frameLocator('#preview').getByRole('heading',{name:'Недоступное действие',exact:true}).evaluate(node=>{
    const main=parent.document.querySelector('main');
    main.scrollTop+=node.getBoundingClientRect().top+window.frameElement.getBoundingClientRect().top-main.getBoundingClientRect().top-24;
  });
  await expect(toc.getByRole('link',{name:'Недоступное действие',exact:true})).toHaveAttribute('aria-current','location');
  await page.locator('main').evaluate(node=>node.scrollTop=0);
  await chooseCatalogueScope(page,'appearance','dark');
  await expect(toc.locator('ul ul a')).toHaveCount(6);
  await expect.poll(()=>page.locator('main').evaluate(node=>node.scrollTop)).toBe(0);
  await page.getByRole('button',{name:'Сравнить 4 режима'}).click();
  await expect(toc.locator('ul ul a')).toHaveCount(6);
  await partial.click();
  await expect(page.frameLocator('#preview-0').getByRole('heading',{name:'Частичный выбор',exact:true})).toBeFocused();
  await expect(partial).toHaveAttribute('aria-current','location');
  await page.setViewportSize({width:1500,height:500});
  await expect.poll(()=>page.locator('.page-contents').evaluate(node=>node.getBoundingClientRect().bottom<=document.querySelector('main').getBoundingClientRect().bottom)).toBe(true);
  await toc.getByRole('link',{name:'Токены',exact:true}).click();
  await expect(toc.getByRole('link',{name:'Токены',exact:true})).toHaveAttribute('aria-current','location');
  expect(await page.locator('.page-contents').evaluate(node=>node.scrollTop)).toBeGreaterThan(0);
  await page.setViewportSize({width:390,height:844});
  await page.locator('.page-contents summary').click();
  await toc.getByRole('link',{name:'Обычный выбор',exact:true}).click();
  await expect(page.frameLocator('#preview-0').getByRole('heading',{name:'Обычный выбор',exact:true})).toBeFocused();
  await expect(toc).toBeHidden();
});

